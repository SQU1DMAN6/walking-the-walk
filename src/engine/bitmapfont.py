_CHAR_W = 8
_CHAR_H = 12


def text_surface(text, colour=(200, 200, 200), spacing=2):
    """Render text to a pygame Surface using the embedded bitmap font.

    Args:
        text: String to render (supports newlines with \n).
        colour: RGB tuple.
        spacing: Horizontal spacing between characters.

    Returns:
        pygame.Surface with text rendered.
    """
    if not text:
        return pygame.Surface((0, 0), pygame.SRCALPHA)

    lines = text.split('\n')
    max_len = max(len(l) for l in lines) if lines else 0

    total_w = max_len * (_CHAR_W + spacing) + spacing
    total_h = len(lines) * (_CHAR_H + 4)

    surf = pygame.Surface((total_w, total_h), pygame.SRCALPHA)
    surf.fill((0, 0, 0, 0))

    for li, line in enumerate(lines):
        y = li * (_CHAR_H + 4)
        x = spacing
        for ch in line:
            if ch in _CHARS:
                data = _CHARS[ch]
                for row in range(_CHAR_H):
                    if row >= len(data):
                        break
                    byte = data[row]
                    if byte == 0:
                        continue
                    for col in range(_CHAR_W):
                        if byte & (0x80 >> col):
                            surf.set_at((x + col, y + row), colour)
            x += _CHAR_W + spacing

    return surf
